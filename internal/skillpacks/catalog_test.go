// assertSameSet fails the test unless got and want contain the same names,
// order-independent.
func assertSameSet(t *testing.T, label string, got, want []string) {
	t.Helper()
	gotSorted := append([]string(nil), got...)
	wantSorted := append([]string(nil), want...)
	sort.Strings(gotSorted)
	sort.Strings(wantSorted)
	if !equalStrings(gotSorted, wantSorted) {
		t.Errorf("%s names = %v, want %v", label, gotSorted, wantSorted)
	}
}

func TestValidIDs_SortedAndMatchesCatalog(t *testing.T) {
	t.Parallel()

	ids := ValidIDs()
	if len(ids) != 3 {
		t.Fatalf("len(ValidIDs()) = %d, want 3", len(ids))
	}
	if !sort.StringsAreSorted(ids) {
		t.Errorf("ValidIDs() = %v, want sorted", ids)
	}
	for _, id := range ids {
		if _, ok := Lookup(id); !ok {
			t.Errorf("ValidIDs() contains %q, but Lookup(%q) failed", id, id)
		}
	}
}

// TestCatalogIDs_MatchWelcomeExtensionAllowlist is the registry contract
// test: internal/content/templates/vscode-bootstrap-welcome.js keeps its
// own PACKS allowlist (a parallel JS enum, since the extension never reads
// Go source), and a source-layout change to one side without the other is
// exactly the class of drift that caused the Matt Pocock discovery failure
// this whole redesign responds to. This test only READS the JS file — it
// never modifies template content.
func TestCatalogIDs_MatchWelcomeExtensionAllowlist(t *testing.T) {
	t.Parallel()

	data, err := os.ReadFile("../content/templates/vscode-bootstrap-welcome.js")
	if err != nil {
		t.Fatalf("read welcome template: %v", err)
	}

	re := regexp.MustCompile(`(?s)const PACKS = \[(.*?)\];`)
	m := re.FindSubmatch(data)
	if m == nil {
		t.Fatal("could not find `const PACKS = [...]` in vscode-bootstrap-welcome.js — has the allowlist been renamed?")
	}
	idRe := regexp.MustCompile(`"([a-z0-9-]+)"`)
	idMatches := idRe.FindAllStringSubmatch(string(m[1]), -1)
	if len(idMatches) == 0 {
		t.Fatal("PACKS array parsed as empty")
	}
	jsIDs := make([]string, 0, len(idMatches))
	for _, im := range idMatches {
		jsIDs = append(jsIDs, im[1])
	}
	sort.Strings(jsIDs)

	goIDs := ValidIDs()
	if len(jsIDs) != len(goIDs) {
		t.Fatalf("welcome.js PACKS = %v, Go catalog = %v — length mismatch", jsIDs, goIDs)
	}
	for i := range goIDs {
		if jsIDs[i] != goIDs[i] {
			t.Errorf("welcome.js PACKS = %v, Go catalog ValidIDs() = %v — must match exactly", jsIDs, goIDs)
			break
		}
	}
}

// TestCatalog_SelectionGranularity_MattSubsetSuperpowersAtomic pins
// spec-skill-packs.md §1's closing rule that selection granularity is an
// axis of its own: both packs are reviewed skill by skill, yet only Matt
// offers a subset (§4.2) while Superpowers installs whole or not at all
// (§5). SelectionAtomic is the zero value, so a newly catalogued pack has
// to opt IN to offering a subset rather than inheriting one by omission.
func TestCatalog_SelectionGranularity_MattSubsetSuperpowersAtomic(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct {
		id       string
		want     SelectionGranularity
		isAtomic bool
	}{
		{id: "matt-pocock-skills", want: SelectionSubset, isAtomic: false},
		{id: "superpowers", want: SelectionAtomic, isAtomic: true},
	} {
		pack, ok := Lookup(tc.id)
		if !ok {
			t.Fatalf("Lookup(%q) not found", tc.id)
		}
		if pack.Selection != tc.want {
			t.Errorf("%s Selection = %v, want %v", tc.id, pack.Selection, tc.want)
		}
		if got := pack.IsAtomic(); got != tc.isAtomic {
			t.Errorf("%s IsAtomic() = %v, want %v", tc.id, got, tc.isAtomic)
		}
	}
}

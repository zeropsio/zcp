func TestLookup_KnownAndUnknown(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name   string
		id     string
		wantOK bool
	}{
		{name: "matt-pocock-skills is known", id: "matt-pocock-skills", wantOK: true},
		{name: "superpowers is known", id: "superpowers", wantOK: true},
		{name: "andrej-karpathy-skills is known", id: "andrej-karpathy-skills", wantOK: true},
		{name: "unknown id", id: "not-a-real-pack", wantOK: false},
		// Retired from the catalog: ZCP already ships Anthropic's agent, so
		// offering Anthropic's own skills as a third-party pack was noise.
		// A manifest-recorded install stays removable (Remove/PackSet do not
		// consult the catalog) — see TestRemove_RetiredPack_StillRemovable
		// and TestPackSet_RetiredPack_RemovableViaSet.
		{name: "anthropic-skills is retired", id: "anthropic-skills", wantOK: false},
		{name: "gstack is deliberately excluded (56MB whole-repo, not a skills collection)", id: "gstack", wantOK: false},
		{name: "empty id", id: "", wantOK: false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			pack, ok := Lookup(tt.id)
			if ok != tt.wantOK {
				t.Fatalf("Lookup(%q) ok = %v, want %v", tt.id, ok, tt.wantOK)
			}
			if !ok {
				return
			}
			if pack.ID != tt.id {
				t.Errorf("pack.ID = %q, want %q", pack.ID, tt.id)
			}
			if pack.Ref == "" {
				t.Errorf("pack.Ref is empty for %q", tt.id)
			}
			if pack.Title == "" || pack.Description == "" {
				t.Errorf("pack %q missing title/description", tt.id)
			}
		})
	}
}

// TestCatalog_MattSupportedSet_Exactly21Grouped pins spec-skill-packs.md
// §4.1's exact 21-skill table, transcribed independently from the spec (not
// generated by reading the catalog back): 17 Engineering + 4 Productivity.
// Personal, miscellaneous, in-progress, and deprecated upstream skills must
// never appear. grill-me is deliberately excluded: its upstream body is a
// thin "run /grilling" wrapper, a duplicate picker entry that overlaps
// grilling's own description, and a subset-selection hazard if picked alone.
func TestCatalog_MattSupportedSet_Exactly21Grouped(t *testing.T) {
	t.Parallel()

	wantEngineering := []string{
		"ask-matt", "diagnosing-bugs", "grill-with-docs", "triage",
		"improve-codebase-architecture", "setup-matt-pocock-skills", "tdd",
		"to-spec", "to-tickets", "wayfinder", "implement", "prototype",
		"research", "domain-modeling", "codebase-design", "code-review",
		"resolving-merge-conflicts",
	}
	wantProductivity := []string{"grilling", "handoff", "teach", "writing-great-skills"}

	pack, ok := Lookup("matt-pocock-skills")
	if !ok {
		t.Fatal("matt-pocock-skills missing from catalog")
	}
	if pack.Review != ReviewSkillLevel {
		t.Fatalf("matt-pocock-skills Review = %v, want ReviewSkillLevel", pack.Review)
	}
	if len(pack.Skills) != 21 {
		t.Fatalf("len(pack.Skills) = %d, want 21", len(pack.Skills))
	}

	byCategory := map[string][]string{}
	seenNames := map[string]bool{}
	for _, sk := range pack.Skills {
		if sk.Name == "" || sk.SourcePath == "" || sk.Category == "" || sk.Description == "" {
			t.Errorf("skill %+v missing a required field", sk)
		}
		if seenNames[sk.Name] {
			t.Errorf("duplicate skill name %q in matt-pocock-skills catalog", sk.Name)
		}
		seenNames[sk.Name] = true
		byCategory[sk.Category] = append(byCategory[sk.Category], sk.Name)
	}

	if len(byCategory) != 2 {
		t.Fatalf("categories = %v, want exactly 2 (Engineering, Productivity)", byCategory)
	}
	assertSameSet(t, "Engineering", byCategory["Engineering"], wantEngineering)
	assertSameSet(t, "Productivity", byCategory["Productivity"], wantProductivity)

	for _, sk := range pack.Skills {
		var wantPrefix string
		switch sk.Category {
		case "Engineering":
			wantPrefix = "skills/engineering/"
		case "Productivity":
			wantPrefix = "skills/productivity/"
		}
		if want := wantPrefix + sk.Name; sk.SourcePath != want {
			t.Errorf("skill %q SourcePath = %q, want %q", sk.Name, sk.SourcePath, want)
		}
	}
}

